    <h4 class="h4_top">Création d'une marque fictive trouvable en grande surface</h4>
    <p id="paragraphe">
        <br>
        L’objectif de ce projet est de créer une marque fictive de produits alimentaires, qui pourrait être commercialisée en grande surface. Il s’agit de concevoir un concept global, incluant le nom de la marque, le logo, l’identité visuelle, les packagings et les supports de communication.
        <br>
         Objectifs <br>
         Présentation de Crookie – Marque et univers graphique

         Crookie est une marque fictive de produits alimentaires pensée pour le rayon snacking des grandes surfaces. Elle propose une identité visuelle à la fois ludique, accessible et gourmande, parfaitement adaptée à un public jeune et familial.
         
         Le nom Crookie est une combinaison astucieuse entre "crook" (filou en anglais) et "cookie". Il évoque l’idée d’un biscuit "croqué", tout en suggérant un personnage espiègle et attachant. Cette identité est incarnée par un logo illustré représentant un cookie aux pépites de chocolat, doté d’un visage expressif, d’un grand sourire et d’un regard malicieux. Le biscuit a un coin croqué, renforçant visuellement le jeu de mot du nom.
         
         Le personnage de Crookie est dessiné en mouvement, avec des bras et jambes animés, pour transmettre une sensation d’énergie, de fun et de dynamisme. Le tout repose sur un fond jaune-orangé (HEX #f9b333), couleur chaleureuse qui évoque la gourmandise, le soleil, et l’accessibilité.
         
         La typographie utilisée pour le nom Crookie est épaisse, noire, arrondie, ce qui accentue le côté accueillant, moderne et enfantin de la marque, tout en restant lisible et impactant.
         
         Le logo se décline en plusieurs versions :
         
         Une version horizontale (personnage au-dessus du nom)
         
         Une version verticale (personnage à côté du nom)
         
         Et des déclinaisons en noir et blanc pour s’adapter aux supports variés (impression, packaging, signalétique...).
         
         Cette charte graphique pose les fondations d’un univers cohérent, prêt à être décliné sur les packagings, les affiches, les présentoirs et les supports digitaux. Crookie se positionne donc comme une marque qui allie plaisir visuel, gourmandise et originalité, tout en restant simple et mémorable.
