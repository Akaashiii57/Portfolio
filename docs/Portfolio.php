        <br>
        Projet UX/UI – Application mobile

        Ce projet est une refonte complète de l’interface mobile de l’application All Bikes Out, un service citoyen permettant aux utilisateurs de signaler des vélos défectueux, perdus ou à rechercher dans les espaces publics. L’objectif de cette refonte était à la fois graphique et fonctionnel : rendre l’interface plus lisible, moderne, et intuitive tout en améliorant l’expérience utilisateur.
        
        🧩 Objectifs du projet :
        Clarifier les actions principales dès l’écran d’accueil.
        
        Optimiser l’ergonomie mobile (navigation, contrastes, hiérarchie visuelle).
        
        Apporter une cohérence graphique entre les différentes sections de l’app.
        
        Créer un design simple, épuré et accessible à tous les profils d’utilisateurs.
        
        🎯 Fonctionnalités repensées :
        Accueil
        Trois boutons clairs :
        🔧 Signaler un vélo défaillant
        🔍 Rechercher un vélo
        🆘 Signaler un vélo perdu
        
        Chaque bouton est associé à une icône explicite, un fond contrasté, et un rappel dans la barre de navigation inférieure, pour un accès rapide à tout moment.
        
        Signaler un vélo défaillant
        Formulaire simple avec numéro du vélo et cases à cocher : roue crevée, chaîne déraillée, sonnette HS, etc.
        
        Le bouton “Signaler” est mis en avant avec une couleur spécifique (bleu), renforçant l’action à valider.
        
        Deux variantes visuelles testées : l’une avec un fond noir pour les champs, l’autre avec une esthétique plus légère.
        
        Signaler un vélo perdu
        Formulaire élargi avec :
        
        Numéro du vélo
        
        Adresse
        
        Coordonnées GPS
        
        Option pour partager sa position en direct
        
        L’interface reste sobre et intuitive, permettant de remplir rapidement le signalement même en situation d’urgence.
