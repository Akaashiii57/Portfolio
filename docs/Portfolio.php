La composition spatiale, en jouant sur les hauteurs et les distances entre les personnages pour créer une profondeur.

Les effets de lumière et d’aura, renforçant la puissance des personnages en combat.

Le reflet dans l’eau, utilisé pour donner un rendu plus réaliste et immersif à la scène.

L’ajout d’éléments emblématiques, comme la Tour du Palais de Dieu, intégrée au centre pour rappeler l’univers mystique et céleste de Dragon Ball.

