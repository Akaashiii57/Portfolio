L’affiche met en scène plusieurs personnages iconiques positionnés dans un décor naturel fidèle à l’esprit de la série : un environnement montagneux, baigné de lumière, avec des reliefs reflétés dans une eau calme. On y retrouve une tension dramatique, avec deux Super Saiyan prêts à lancer une attaque d’énergie, capturant ainsi l’intensité des combats typiques de la série.

