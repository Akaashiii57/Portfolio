Les effets de lumière, d’aura et de posture, qui rappellent les codes des combats épiques dans les mangas et animés.

Une composition cinématographique, avec un équilibre entre le vide du ciel et la densité du décor en bas à droite, guidant naturellement le regard vers la zone d’action.

