    <h4 class="h4_top">Présentation de Kunel Gaur – Projet de redesign packaging</h4>
    <p id="paragraphe">
        <br>

        Ce projet s’inspire de la vision artistique et minimaliste de Kunel Gaur, un designer indien reconnu pour ses travaux mêlant typographie, contraste et mise en page brute. L’objectif ici est de réinterpréter les packagings de grandes marques alimentaires à travers une approche graphique radicale, en les réduisant à leur essence typographique et iconographique.

Chaque produit iconique (Panzani, Bonne Maman, Kit Kat, Lulu, Géant Vert...) est repensé dans une version monochrome en noir et blanc, avec une mise en page centrée sur :

Une typographie sans serif simple, souvent fine, rigide et élégante.

Des illustrations réduites à des pictogrammes, utilisés comme symboles plutôt que comme images décoratives.

Une composition épurée, basée sur des axes verticaux et horizontaux forts, avec des zones d’ombre maîtrisées.

Le choix du noir sur blanc (ou inversement) crée un effet éditorial et muséal, comme si chaque produit devenait une œuvre graphique à exposer. On ne parle plus ici d’ultra-gourmandise ou de couleurs attractives : le regard est focalisé sur la forme, le texte, la hiérarchie des informations.

Ce projet questionne la place du design dans notre quotidien. Il propose une rupture volontaire avec les codes traditionnels du marketing alimentaire, en imaginant une gamme de produits où l’identité visuelle serait dictée par la lisibilité, la sobriété et la cohérence graphique, à la manière d’un travail éditorial ou artistique.
